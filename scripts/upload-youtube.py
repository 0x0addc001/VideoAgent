#!/usr/bin/env python3
"""Upload a video to YouTube with the OAuth installed-app flow.

Setup (one time):
  1. Google Cloud Console -> create a project.
  2. Enable "YouTube Data API v3".
  3. OAuth consent screen -> External -> add your account as a test user.
  4. Credentials -> Create credentials -> OAuth client ID -> Desktop app.
  5. Download the JSON and point YOUTUBE_CLIENT_SECRETS at it.

Run:
  uv run --with google-api-python-client --with google-auth-oauthlib \\
    python scripts/upload-youtube.py --file /path/to/promo.mp4 \\
    --title "VideoAgent — You Are the Director" \\
    --description "Generated by VideoAgent." --privacy unlisted

The script prints a Google consent URL. Open it in a browser, approve, and
the localhost callback stores an offline token. The token is written with 0600
permissions under ~/.config/videoagent and never enters the repository.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials
from google_auth_oauthlib.flow import InstalledAppFlow
from googleapiclient.discovery import build
from googleapiclient.http import MediaFileUpload

SCOPES = ["https://www.googleapis.com/auth/youtube.upload"]
DEFAULT_TOKEN = Path("~/.config/videoagent/youtube-token.json").expanduser()
DEFAULT_PORT = 8765


def load_credentials(client_secrets: Path, token_path: Path) -> Credentials:
    credentials: Credentials | None = None
    if token_path.exists():
        credentials = Credentials.from_authorized_user_file(str(token_path), SCOPES)
    if credentials and credentials.expired and credentials.refresh_token:
        credentials.refresh(Request())
    if credentials and credentials.valid:
        return credentials
    if not client_secrets.exists():
        raise SystemExit(
            f"Missing OAuth client JSON at {client_secrets}.\n"
            "Create a Desktop-app OAuth client and set YOUTUBE_CLIENT_SECRETS."
        )
    flow = InstalledAppFlow.from_client_secrets_file(str(client_secrets), SCOPES)
    credentials = flow.run_local_server(
        port=DEFAULT_PORT,
        open_browser=False,
        authorization_prompt_message="Open this URL to authorize YouTube upload:\n{url}",
        success_message="YouTube authorization received. You can close this tab.",
    )
    token_path.parent.mkdir(parents=True, exist_ok=True)
    token_path.write_text(credentials.to_json(), encoding="utf-8")
    token_path.chmod(0o600)
    return credentials


def main() -> None:
    parser = argparse.ArgumentParser(description="Upload a video to YouTube.")
    parser.add_argument("--file", required=True, type=Path)
    parser.add_argument("--title", required=True)
    parser.add_argument("--description", default="Generated by VideoAgent.")
    parser.add_argument("--privacy", choices=["private", "unlisted", "public"], default="unlisted")
    parser.add_argument("--tags", default="VideoAgent,AI video,video IDE")
    args = parser.parse_args()

    if not args.file.is_file():
        raise SystemExit(f"Video not found: {args.file}")

    client_secrets = Path(
        os.environ.get(
            "YOUTUBE_CLIENT_SECRETS",
            "~/.config/videoagent/youtube-client.json",
        )
    ).expanduser()
    token_path = Path(os.environ.get("YOUTUBE_TOKEN", str(DEFAULT_TOKEN))).expanduser()

    credentials = load_credentials(client_secrets, token_path)
    youtube = build("youtube", "v3", credentials=credentials)
    request = youtube.videos().insert(
        part="snippet,status",
        body={
            "snippet": {
                "title": args.title[:100],
                "description": args.description[:5000],
                "tags": [tag.strip() for tag in args.tags.split(",") if tag.strip()],
                "categoryId": "28",
            },
            "status": {
                "privacyStatus": args.privacy,
                "selfDeclaredMadeForKids": False,
            },
        },
        media_body=MediaFileUpload(str(args.file), chunksize=8 * 1024 * 1024, resumable=True),
    )
    response = request.execute()
    video_id = response["id"]
    print(f"Uploaded: https://youtu.be/{video_id}")
    print(f"Studio: https://studio.youtube.com/video/{video_id}/edit")


if __name__ == "__main__":
    sys.exit(main())
